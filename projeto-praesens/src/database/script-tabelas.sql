CREATE DATABASE praesens;

USE praesens;

CREATE TABLE usuario (
    idUsuario INT PRIMARY KEY AUTO_INCREMENT,
    nome VARCHAR(80) NOT NULL,
    email VARCHAR(80) NOT NULL UNIQUE,
    senha VARCHAR(45) NOT NULL,
    dtCadastro DATETIME DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE pratica (
    idPratica INT PRIMARY KEY AUTO_INCREMENT,
    fkUsuario INT NOT NULL,
    dtHora DATETIME DEFAULT CURRENT_TIMESTAMP,
    duracaoSegundos INT NOT NULL,
    ciclos INT NOT NULL,
    FOREIGN KEY (fkUsuario) REFERENCES usuario(idUsuario)
);

CREATE TABLE diario (
    idDiario INT PRIMARY KEY AUTO_INCREMENT,
    fkPratica INT NOT NULL UNIQUE,
    texto TEXT NOT NULL,
    dtHora DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (fkPratica) REFERENCES pratica(idPratica)
);